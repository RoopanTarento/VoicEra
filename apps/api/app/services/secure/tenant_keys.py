"""Per-adopter key hierarchy (envelope encryption).

Every adopter (VoicEra organisation) gets its own pair of 256-bit keys:

* a data-encryption key (DEK) for AES-256-GCM over phone numbers and emails,
* an HMAC key for the keyed hash used to match and de-duplicate numbers.

Both are generated by VoicEra and stored only *wrapped*: encrypted with the
platform master key (``SECURE_VAULT_KEYS``) and bound by associated data to
the adopter and key version, so a wrapped key copied to another adopter does
not unwrap. One adopter's keys can be rotated, suspended or revoked without
touching any other adopter. Revoking destroys the wrapped keys, which makes
every stored number of that adopter permanently unreadable (crypto-shredding
for offboarding).

``SecureTenantKeys`` document::

    {org_id, status: active|suspended|revoked, active_version: "v2",
     versions: [{version, status: active|retired|destroyed, master_version,
                 dek: {nonce, ciphertext}, hmac: {nonce, ciphertext},
                 created_at, retired_at}],
     created_at, updated_at, revoked_at}

Unwrapped keys are cached in-process for ``CACHE_TTL_SECONDS``; another
process sees a suspension or revocation within that window.
"""

from __future__ import annotations

import base64
import hashlib
import os
import threading
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from pymongo import ReturnDocument
from pymongo.database import Database

from app.database import get_database
from app.services.secure.keys import KEY_BYTES, VaultKeyError, get_key_provider

COLLECTION = "SecureTenantKeys"
CACHE_TTL_SECONDS = 60.0

STATUS_ACTIVE = "active"
STATUS_SUSPENDED = "suspended"
STATUS_REVOKED = "revoked"


class TenantKeyUnavailable(VaultKeyError):
    """The adopter's keys are suspended, revoked or cannot be unwrapped."""

    def __init__(self, message: str, *, reason: str) -> None:
        self.reason = reason
        super().__init__(message)


@dataclass(frozen=True)
class TenantKeyring:
    org_id: str
    active_version: str
    _deks: dict[str, bytes]
    _hmacs: dict[str, bytes]

    def dek(self, version: str) -> bytes:
        try:
            return self._deks[version]
        except KeyError as exc:
            raise TenantKeyUnavailable(
                f"Adopter key version {version} is not available", reason="unknown_version"
            ) from exc

    def hmac_key(self, version: str | None = None) -> bytes:
        return self._hmacs[version or self.active_version]

    def versions(self) -> list[str]:
        return sorted(self._deks)

    def fingerprint(self, version: str) -> str:
        return hashlib.sha256(b"voicera-tenant-fp" + self.dek(version)).hexdigest()[:12]

    def __repr__(self) -> str:  # never print key material
        return f"TenantKeyring(org_id={self.org_id!r}, active={self.active_version!r}, versions={self.versions()!r})"


_cache: dict[str, tuple[float, TenantKeyring]] = {}
_lock = threading.Lock()


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def ensure_indexes(db: Database | None = None) -> None:
    db = db if db is not None else get_database()
    db[COLLECTION].create_index("org_id", unique=True, name="org_id_unique")


def invalidate(org_id: str | None = None) -> None:
    with _lock:
        if org_id is None:
            _cache.clear()
        else:
            _cache.pop(org_id, None)


def _aad(org_id: str, version: str, kind: str) -> bytes:
    return f"voicera-tenant-key:v1:{org_id}:{version}:{kind}".encode("utf-8")


def _wrap(raw: bytes, *, org_id: str, version: str, kind: str) -> tuple[str, dict[str, str]]:
    master = get_key_provider()
    master_version = master.active_version
    nonce = os.urandom(12)
    ciphertext = AESGCM(master.data_key(master_version)).encrypt(nonce, raw, _aad(org_id, version, kind))
    return master_version, {
        "nonce": base64.b64encode(nonce).decode("ascii"),
        "ciphertext": base64.b64encode(ciphertext).decode("ascii"),
    }


def _unwrap(blob: dict[str, str], *, master_version: str, org_id: str, version: str, kind: str) -> bytes:
    master = get_key_provider()
    try:
        return AESGCM(master.data_key(master_version)).decrypt(
            base64.b64decode(blob["nonce"]),
            base64.b64decode(blob["ciphertext"]),
            _aad(org_id, version, kind),
        )
    except (InvalidTag, KeyError, ValueError) as exc:
        raise TenantKeyUnavailable(
            "Adopter key failed to unwrap with the master key", reason="unwrap_failed"
        ) from exc


def _new_version_entry(org_id: str, version: str) -> dict[str, Any]:
    dek = os.urandom(KEY_BYTES)
    hmac_key = os.urandom(KEY_BYTES)
    master_version, wrapped_dek = _wrap(dek, org_id=org_id, version=version, kind="dek")
    _, wrapped_hmac = _wrap(hmac_key, org_id=org_id, version=version, kind="hmac")
    return {
        "version": version,
        "status": STATUS_ACTIVE,
        "master_version": master_version,
        "dek": wrapped_dek,
        "hmac": wrapped_hmac,
        "created_at": _now(),
        "retired_at": None,
    }


def provision(org_id: str) -> dict[str, Any]:
    """Create the adopter's first key version if it has none (idempotent)."""
    col = get_database()[COLLECTION]
    existing = col.find_one({"org_id": org_id})
    if existing:
        return existing
    now = _now()
    doc = {
        "org_id": org_id,
        "status": STATUS_ACTIVE,
        "active_version": "v1",
        "versions": [_new_version_entry(org_id, "v1")],
        "created_at": now,
        "updated_at": now,
        "revoked_at": None,
    }
    try:
        col.insert_one(dict(doc))
    except Exception:
        # Another process provisioned concurrently; use theirs.
        found = col.find_one({"org_id": org_id})
        if found:
            return found
        raise
    return doc


def get_record(org_id: str) -> dict[str, Any] | None:
    return get_database()[COLLECTION].find_one({"org_id": org_id}, {"_id": 0})


def keyring(org_id: str, *, provision_missing: bool = True) -> TenantKeyring:
    """Unwrapped keys for ``org_id``; raises TenantKeyUnavailable when not usable."""
    if not org_id:
        raise TenantKeyUnavailable("Adopter is required", reason="no_org")
    get_key_provider()  # fail fast, before any database access, when no master key is configured
    now = time.monotonic()
    with _lock:
        cached = _cache.get(org_id)
        if cached and now - cached[0] < CACHE_TTL_SECONDS:
            return cached[1]
    doc = get_database()[COLLECTION].find_one({"org_id": org_id})
    if doc is None:
        if not provision_missing:
            raise TenantKeyUnavailable("Adopter has no keys", reason="not_provisioned")
        doc = provision(org_id)
    status = doc.get("status")
    if status == STATUS_REVOKED:
        raise TenantKeyUnavailable("Adopter keys were revoked; data is unreadable", reason="revoked")
    if status == STATUS_SUSPENDED:
        raise TenantKeyUnavailable("Adopter is suspended", reason="suspended")
    deks: dict[str, bytes] = {}
    hmacs: dict[str, bytes] = {}
    for entry in doc.get("versions") or []:
        if entry.get("status") == "destroyed":
            continue
        v = entry["version"]
        deks[v] = _unwrap(entry["dek"], master_version=entry["master_version"], org_id=org_id, version=v, kind="dek")
        hmacs[v] = _unwrap(entry["hmac"], master_version=entry["master_version"], org_id=org_id, version=v, kind="hmac")
    active = doc.get("active_version")
    if active not in deks:
        raise TenantKeyUnavailable("Adopter active key version is missing", reason="no_active_version")
    ring = TenantKeyring(org_id=org_id, active_version=active, _deks=deks, _hmacs=hmacs)
    with _lock:
        _cache[org_id] = (now, ring)
    return ring


def _save_versions(org_id: str, versions: list[dict[str, Any]], **extra: Any) -> None:
    get_database()[COLLECTION].update_one(
        {"org_id": org_id},
        {"$set": {"versions": versions, "updated_at": _now(), **extra}},
    )
    invalidate(org_id)


def add_version(org_id: str) -> str:
    """Generate a new key version and make it active. Older versions stay decrypt-only."""
    doc = get_database()[COLLECTION].find_one({"org_id": org_id}) or provision(org_id)
    if doc.get("status") != STATUS_ACTIVE:
        raise TenantKeyUnavailable("Only an active adopter's keys can be rotated", reason=str(doc.get("status")))
    versions = list(doc.get("versions") or [])
    numbers = [int(str(e["version"]).lstrip("v") or 0) for e in versions]
    version = f"v{max(numbers, default=0) + 1}"
    now = _now()
    for entry in versions:
        if entry.get("status") == STATUS_ACTIVE:
            entry["status"] = "retired"
            entry["retired_at"] = now
    versions.append(_new_version_entry(org_id, version))
    _save_versions(org_id, versions, active_version=version)
    return version


def destroy_unused_versions(org_id: str, in_use: set[str]) -> list[str]:
    """Delete wrapped material for retired versions no record uses any more."""
    doc = get_database()[COLLECTION].find_one({"org_id": org_id})
    if not doc:
        return []
    versions = list(doc.get("versions") or [])
    destroyed = []
    for entry in versions:
        if entry.get("status") == "retired" and entry["version"] not in in_use:
            entry.update(status="destroyed", dek=None, hmac=None)
            destroyed.append(entry["version"])
    if destroyed:
        _save_versions(org_id, versions)
    return destroyed


def set_status(org_id: str, status: str) -> dict[str, Any]:
    if status not in (STATUS_ACTIVE, STATUS_SUSPENDED):
        raise ValueError("status must be active or suspended")
    provision(org_id)
    doc = get_database()[COLLECTION].find_one_and_update(
        {"org_id": org_id, "status": {"$ne": STATUS_REVOKED}},
        {"$set": {"status": status, "updated_at": _now()}},
        return_document=ReturnDocument.AFTER,
        projection={"_id": 0, "versions": 0},
    )
    invalidate(org_id)
    if doc is None:
        raise TenantKeyUnavailable("Adopter keys were revoked", reason="revoked")
    return doc


def revoke(org_id: str) -> None:
    """Destroy every wrapped key of the adopter. Irreversible."""
    doc = get_database()[COLLECTION].find_one({"org_id": org_id}) or provision(org_id)
    versions = [
        {**e, "status": "destroyed", "dek": None, "hmac": None} for e in doc.get("versions") or []
    ]
    _save_versions(org_id, versions, status=STATUS_REVOKED, revoked_at=_now())


def rewrap_all(*, master_version: str | None = None) -> dict[str, int]:
    """Re-wrap every adopter's keys under the active master key version.

    Run after adding a new master key and making it active; the data itself
    is untouched, so this is fast even for large vaults.
    """
    master = get_key_provider()
    target = master_version or master.active_version
    rewrapped = 0
    skipped = 0
    col = get_database()[COLLECTION]
    for doc in col.find({"status": {"$ne": STATUS_REVOKED}}):
        org_id = doc["org_id"]
        changed = False
        versions = []
        for entry in doc.get("versions") or []:
            if entry.get("status") == "destroyed" or entry.get("master_version") == target:
                versions.append(entry)
                continue
            v = entry["version"]
            dek = _unwrap(entry["dek"], master_version=entry["master_version"], org_id=org_id, version=v, kind="dek")
            hm = _unwrap(entry["hmac"], master_version=entry["master_version"], org_id=org_id, version=v, kind="hmac")
            mv, wdek = _wrap(dek, org_id=org_id, version=v, kind="dek")
            _, whm = _wrap(hm, org_id=org_id, version=v, kind="hmac")
            versions.append({**entry, "master_version": mv, "dek": wdek, "hmac": whm})
            changed = True
        if changed:
            col.update_one({"org_id": org_id}, {"$set": {"versions": versions, "updated_at": _now()}})
            rewrapped += 1
        else:
            skipped += 1
    invalidate()
    return {"rewrapped_adopters": rewrapped, "already_current": skipped, "master_version": target}


def summary(org_id: str) -> dict[str, Any]:
    """Display-safe view of an adopter's keys (no key material)."""
    doc = get_record(org_id) or {}
    return {
        "status": doc.get("status", "not_provisioned"),
        "active_version": doc.get("active_version"),
        "versions": [
            {
                "version": e.get("version"),
                "status": e.get("status"),
                "master_version": e.get("master_version"),
                "created_at": e.get("created_at"),
                "retired_at": e.get("retired_at"),
            }
            for e in doc.get("versions") or []
        ],
        "created_at": doc.get("created_at"),
        "revoked_at": doc.get("revoked_at"),
    }
